import { randomUUID } from "node:crypto";
import { Prisma, PrismaClient } from "@prisma/client";
import { StockAddedEvent } from "../../modules/inventory-management/domain/entities/stock.entity";

function fixtureIds() {
  return {
    product: randomUUID(),
    variant: randomUUID(),
    user: randomUUID(),
    reminder: randomUUID(),
    location: randomUUID(),
  };
}

async function createFixtures(tx: Prisma.TransactionClient, ids: ReturnType<typeof fixtureIds>) {
  await tx.product.create({
    data: {
      id: ids.product,
      title: "Isolated restock probe",
      slug: `restock-probe-${ids.product}`,
      price: 10,
    },
  });
  await tx.productVariant.create({
    data: { id: ids.variant, productId: ids.product, sku: `PROBE-${ids.variant}`, price: 10 },
  });
  await tx.user.create({
    data: { id: ids.user, email: `restock-${ids.user}@example.invalid`, isGuest: true },
  });
  await tx.location.create({
    data: { id: ids.location, name: `Restock probe ${ids.location}`, type: "warehouse" },
  });
  await tx.reminder.create({
    data: {
      id: ids.reminder,
      type: "restock",
      variantId: ids.variant,
      userId: ids.user,
      contact: "email",
      channel: "email",
      status: "pending",
      optInAt: new Date(),
    },
  });
}

/** Persistence-only probe: all fixtures are rolled back, including on assertion failures. */
export async function runRestockReminderProbe(prisma: PrismaClient): Promise<void> {
  const ids = fixtureIds();
  const rollback = new Error("Expected restock probe rollback");
  try {
    await prisma.$transaction(async (tx) => {
      await createFixtures(tx, ids);
      const record = await tx.reminder.findUnique({
        where: { id: ids.reminder },
        select: { status: true, optInAt: true },
      });
      if (
        record?.status !== "pending" ||
        !record.optInAt ||
        (await tx.reminder.count({ where: { variantId: ids.variant } })) !== 1
      ) {
        throw new Error("Restock reminder persistence assertion failed");
      }
      throw rollback;
    });
  } catch (error) {
    if (error !== rollback) throw error;
  }
  if (
    (await prisma.product.findUnique({ where: { id: ids.product } })) ||
    (await prisma.reminder.findUnique({ where: { id: ids.reminder } }))
  ) {
    throw new Error("Restock probe rollback left fixture records");
  }
}

/** Tests current subscriber state transitions, not real notification delivery. */
export async function runRestockDispatcherProbe(
  prisma: PrismaClient,
  publish: (event: StockAddedEvent) => Promise<void>,
): Promise<void> {
  const ids = fixtureIds();
  const failures: unknown[] = [];
  try {
    await prisma.$transaction((tx) => createFixtures(tx, ids));
    // InMemoryEventBus awaits handlers; a fixed sleep does not establish completion.
    await publish(new StockAddedEvent(ids.variant, ids.location, 5));
    const record = await prisma.reminder.findUnique({
      where: { id: ids.reminder },
      select: { status: true },
    });
    if (record?.status !== "sent") throw new Error("Simulated dispatcher state transition failed");
  } catch (error) {
    failures.push(error);
  }
  try {
    // Scoped IDs are generated by this probe; existing products/subscribers are never selected.
    await prisma.$transaction(async (tx) => {
      await tx.reminder.deleteMany({ where: { id: ids.reminder } });
      await tx.user.deleteMany({ where: { id: ids.user } });
      await tx.product.deleteMany({ where: { id: ids.product } });
      await tx.location.deleteMany({ where: { id: ids.location } });
    });
  } catch (error) {
    failures.push(error);
  }
  if (failures.length === 1) throw failures[0];
  if (failures.length > 1)
    throw new AggregateError(failures, "Restock dispatch and cleanup failed");
}
